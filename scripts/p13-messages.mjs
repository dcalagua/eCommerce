const path = 'src/shared/i18n/messages.ts'
const raw = readFileSync(path, 'utf8')
// El repositorio se edita en Windows y el archivo está en CRLF. Se detecta el
// final de línea y se restituye al escribir: si no, el diff serían 4.100 líneas
// cambiadas en vez de las 250 que se añaden.
const eol = raw.includes('\r\n') ? '\r\n' : '\n'
const lines = raw.split(eol)

/** Índice (0-based) de la línea `  },` que cierra el bloque del idioma dado. */
function closingOf(locale) {
  const open = lines.findIndex((line) => line === `  ${locale}: {`)
  if (open < 0) throw new Error(`No se encontró el bloque ${locale}`)
  for (let i = open + 1; i < lines.length; i += 1) {
    if (lines[i] === '  },') return i
  }
  throw new Error(`El bloque ${locale} no se cierra`)
}

if (lines.some((line) => line.includes(`'nav.analytics'`))) {
  console.log('Las claves de P13 ya están puestas. No se toca nada.')
  process.exit(0)
}

// Primero el bloque MÁS LEJANO: insertar arriba desplazaría el índice de abajo.
const en = closingOf('en')
const es = closingOf('es')
const out = [
  ...lines.slice(0, es),
  ...ES.trim().split('\n'),
  ...lines.slice(es, en),
  ...EN.trim().split('\n'),
  ...lines.slice(en),
]
writeFileSync(path, out.join('\n'), 'utf8')
console.log(`Claves de P13 insertadas: ES en la línea ${es + 1}, EN en la ${en + 1}.`)
